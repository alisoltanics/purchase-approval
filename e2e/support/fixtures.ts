import { FIXTURE_CO_ID } from "./accounts";
import { uuid5 } from "./uuid5";

export type FixtureStatus = "pending" | "approved" | "rejected";

export interface FixtureRequest {
  n: number;
  title: string;
  id: string;
  status: FixtureStatus;
  owner: "eli" | "noa" | "ola";
  submittedMinute: number; // minutes after 2026-09-01 08:00 UTC
}

function statusFor(n: number): FixtureStatus {
  if (n >= 4 && n <= 28) {
    const mod = n % 3;
    return mod === 0 ? "pending" : mod === 1 ? "approved" : "rejected";
  }
  return "pending";
}

function ownerFor(n: number): "eli" | "noa" | "ola" {
  return n <= 3 ? "eli" : n <= 28 ? "noa" : "ola";
}

/** The 45 Fixture Co requests exactly as generated by seed_test_fixtures (docs/seed-spec.md section 4). */
export const fixtureRequests: readonly FixtureRequest[] = Array.from({ length: 45 }, (_, i) => {
  const n = i + 1;
  return {
    n,
    title: `Fixture request ${n}`,
    id: uuid5(FIXTURE_CO_ID, `request-${n}`),
    status: statusFor(n),
    owner: ownerFor(n),
    submittedMinute: Math.floor(n / 4),
  };
});

/** Newest first: submitted_at DESC, then id DESC (plan D-13). */
export function newestFirst(items: readonly FixtureRequest[]): FixtureRequest[] {
  return [...items].sort((a, b) => {
    if (a.submittedMinute !== b.submittedMinute) {
      return b.submittedMinute - a.submittedMinute;
    }
    return a.id < b.id ? 1 : a.id > b.id ? -1 : 0;
  });
}

export function titlesOnPage(items: readonly FixtureRequest[], page: number): string[] {
  return newestFirst(items)
    .slice((page - 1) * 20, page * 20)
    .map((r) => r.title);
}
